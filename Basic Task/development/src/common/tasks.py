TASKS_BY_ID = {t["id"]: t for t in TASKS}


def get(task_id):
    """按编号取任务，找不到抛 KeyError 并给出可用编号"""
    t = TASKS_BY_ID.get(task_id)
    if t is None:
        raise KeyError(
            f"没有任务编号 {task_id!r}；可用编号：{', '.join(TASKS_BY_ID)}")
    return t


def all_ids():
    return [t["id"] for t in TASKS]


def describe():
    """给日志/README 用的任务清单"""
    lines = []
    for t in TASKS:
        f = t["file"] or "—"
        lines.append(f"  {t['id']}  {t['kind']:<6} {f:<38} {t['title']}")
    return "\n".join(lines)


